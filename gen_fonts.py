"""Build-time font rasteriser for news-image-20261118 v4.

Runs LOCALLY only (never in the make.fun sandbox). Uses PIL + the system
DejaVu fonts to rasterise glyphs into a compact 2-bit-grayscale bitmap
font, and writes fontdata.py next to this file.

The sandbox entry point (main.py) is pure standard library: it imports
fontdata.py (data shipped in the repo) and draws everything itself.

Usage:  python3 gen_fonts.py
Output: fontdata.py  (FONTS dict: one long string per font variant)
"""

import json
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("PIL is required to build the font data (local tool only).")

HERE = os.path.dirname(os.path.abspath(__file__))

# (family, size) pairs we actually use in the layout.
FONTS = [
    ("serif-bold", "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf", 40),
    ("serif-bold", "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf", 22),
    ("serif-bold", "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf", 17),
    ("sans-bold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 16),
    ("sans-bold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 13),
    ("sans-bold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 11),
    ("sans", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 12),
    ("sans", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 11),
    ("sans", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 10),
]

# ASCII printable + the few non-ASCII marks the copy uses.
CHARS = (
    [chr(c) for c in range(32, 127)]
    + ["\u2013", "\u2014", "\u2018", "\u2019", "\u201c", "\u201d",
       "\u00b7", "\u00d7", "\u2022"]
)


def rasterise(path, size):
    """Return {char: (advance, width, height, top, hexdata)} for one font."""
    font = ImageFont.truetype(path, size)
    out = {}
    for ch in CHARS:
        advance = int(round(font.getlength(ch)))
        # Render the glyph alone on a generous canvas, then crop.
        pad = 4
        img = Image.new("L", (size * 3, size * 3), 0)
        draw = ImageDraw.Draw(img)
        draw.text((pad, pad), ch, font=font, fill=255)
        bbox = img.getbbox()
        if bbox is None:
            out[ch] = (advance, 0, 0, 0, "")
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        # top = distance from the text baseline (pad + ascent) to glyph top.
        ascent, _descent = font.getmetrics()
        top = (pad + ascent) - y0
        px = img.crop((x0, y0, x1, y1)).load()
        # Pack 2 bits per pixel, row-major: 0, 85, 170, 255 -> 0..3.
        bits = []
        acc = 0
        nbits = 0
        for yy in range(h):
            for xx in range(w):
                v = px[xx, yy]
                q = 0 if v < 32 else (1 if v < 96 else (2 if v < 192 else 3))
                acc = (acc << 2) | q
                nbits += 2
                if nbits == 8:
                    bits.append(acc)
                    acc = 0
                    nbits = 0
        if nbits:
            bits.append(acc << (8 - nbits))
        out[ch] = (advance, w, h, top, bytes(bits).hex())
    return out


def main():
    lines = []
    lines.append("# Generated by gen_fonts.py (local build tool) from system DejaVu fonts.")
    lines.append("# 2-bit grayscale bitmaps. Do not edit by hand; re-run gen_fonts.py.")
    lines.append("FONTS = {")
    total = 0
    for family, path, size in FONTS:
        glyphs = rasterise(path, size)
        parts = []
        for ch in CHARS:
            adv, w, h, top, hx = glyphs[ch]
            parts.append("%d:%d,%d,%d,%d,%s" % (ord(ch), adv, w, h, top, hx))
            total += len(hx)
        key = "%s-%d" % (family, size)
        lines.append("    %r: %r," % (key, ";".join(parts)))
        print("font %-14s chars=%d hexbytes~%d" % (key, len(parts),
              sum(len(glyphs[c][4]) // 2 for c in CHARS)))
    lines.append("}")
    lines.append("CHARS = %r" % "".join(CHARS))
    out_path = os.path.join(HERE, "fontdata.py")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d bytes, ~%d hex chars of glyph data)"
          % (out_path, os.path.getsize(out_path), total))


if __name__ == "__main__":
    main()
